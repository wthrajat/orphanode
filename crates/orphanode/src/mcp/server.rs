use orphanode::{ExplanationStatus, ProjectScanRequest, explain, scan_project};
use rmcp::handler::server::wrapper::Parameters;
use rmcp::model::{CallToolResult, ContentBlock, Implementation, ServerCapabilities, ServerConfig};
use rmcp::{ServerHandler, tool, tool_handler, tool_router};

use super::arguments::{IssueArguments, ScanArguments, WhyArguments, issue_families, project_root};
use super::reply::{scan_reply, why_reply};
use crate::issue_description;

pub(super) struct OrphanodeTools;

#[tool_router]
impl OrphanodeTools {
    #[tool(
        description = "Find dead code in a JavaScript or TypeScript project: unreachable files, unused exports, declarations, class members, dependencies and workspace packages. Read-only."
    )]
    async fn scan_project(
        &self,
        Parameters(arguments): Parameters<ScanArguments>,
    ) -> CallToolResult {
        let span = tracing::info_span!(
            "tools/call scan_project",
            otel.kind = "server",
            mcp.method.name = "tools/call",
            gen_ai.tool.name = "scan_project",
            otel.status_code = tracing::field::Empty,
            otel.status_description = tracing::field::Empty,
        );
        respond(run_blocking(span, move || scan(&arguments)).await)
    }

    #[tool(
        description = "Explain why orphanode keeps or reports a file or package, with the evidence behind the verdict."
    )]
    async fn why(&self, Parameters(arguments): Parameters<WhyArguments>) -> CallToolResult {
        let span = tracing::info_span!(
            "tools/call why",
            otel.kind = "server",
            mcp.method.name = "tools/call",
            gen_ai.tool.name = "why",
            otel.status_code = tracing::field::Empty,
            otel.status_description = tracing::field::Empty,
        );
        respond(run_blocking(span, move || why(&arguments)).await)
    }

    #[tool(
        description = "Describe an orphanode issue code, such as ORP1002, and when it is safe to act on."
    )]
    async fn explain_issue(
        &self,
        Parameters(arguments): Parameters<IssueArguments>,
    ) -> CallToolResult {
        respond(describe_issue(&arguments.issue_id))
    }
}

#[tool_handler]
#[allow(
    clippy::unused_async_trait_impl,
    reason = "generated by rmcp's tool_handler"
)]
impl ServerHandler for OrphanodeTools {
    fn get_info(&self) -> ServerConfig {
        let capabilities = ServerCapabilities::builder().enable_tools().build();
        let implementation = Implementation::new("orphanode", env!("CARGO_PKG_VERSION"));
        ServerConfig::new(capabilities).with_server_info(implementation)
    }
}

fn scan(arguments: &ScanArguments) -> Result<String, String> {
    let root = project_root(&arguments.root)?;
    let mut request = ProjectScanRequest::new(&root);
    request.issues = issue_families(arguments.issues.as_deref())?;
    request.workspace = arguments.workspace.as_ref().map(Into::into);
    let report = scan_project(&request).map_err(|error| error.to_string())?;
    Ok(scan_reply(&root, report, arguments.max_findings()))
}

fn why(arguments: &WhyArguments) -> Result<String, String> {
    let root = project_root(&arguments.root)?;
    let report =
        scan_project(&ProjectScanRequest::new(&root)).map_err(|error| error.to_string())?;
    let explanation = explain(&report, &arguments.query);
    match explanation.status {
        ExplanationStatus::NotFound => Err(format!(
            "Nothing in the project matches \"{}\"",
            arguments.query
        )),
        _ => Ok(why_reply(&explanation)),
    }
}

fn describe_issue(issue_id: &str) -> Result<String, String> {
    let code = issue_id.trim().to_ascii_uppercase();
    let (title, policy) =
        issue_description(&code).ok_or_else(|| format!("Unknown issue code \"{issue_id}\""))?;
    Ok(format!("{code}  {title}\n\n{policy}"))
}

/// Runs the analysis on a blocking thread inside `span`. The blocking thread
/// doesn't inherit the tool call's `PostHog` request context, so it is scoped
/// again there; spans started during the analysis then join the call's session.
async fn run_blocking(
    span: tracing::Span,
    work: impl FnOnce() -> Result<String, String> + Send + 'static,
) -> Result<String, String> {
    let request_context = posthog_rs::RequestContext::current();
    let runtime = tokio::runtime::Handle::current();
    let work_span = span.clone();
    let traced_work = move || {
        let in_span = move || work_span.in_scope(work);
        match request_context {
            Some(context) => runtime.block_on(context.scope(async move { in_span() })),
            None => in_span(),
        }
    };
    let outcome = tokio::task::spawn_blocking(traced_work)
        .await
        .unwrap_or_else(|error| Err(format!("The analysis stopped unexpectedly: {error}")));
    if let Err(message) = &outcome {
        span.record("otel.status_code", "ERROR");
        span.record("otel.status_description", message.as_str());
    }
    outcome
}

fn respond(outcome: Result<String, String>) -> CallToolResult {
    match outcome {
        Ok(text) => CallToolResult::success(vec![ContentBlock::text(text)]),
        Err(message) => CallToolResult::error(vec![ContentBlock::text(message)]),
    }
}
